#!/usr/bin/env python3
"""Regenerate the matrix in docs/parity.md from docs/parity.json.

    python3 build/parity_md.py           # rewrite docs/parity.md in place
    python3 build/parity_md.py --check   # exit 1 when it is out of date

Only the block between the BEGIN / END markers is generated; the prose
around it is hand-written. tests/test_parity_matrix.py fails when the
block does not match parity.json. Stdlib only; Python 3.9.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import List

ROOT = Path(__file__).resolve().parent.parent
PARITY_JSON = ROOT / "docs" / "parity.json"
PARITY_MD = ROOT / "docs" / "parity.md"
ADAPTERS = ("claude", "codex", "cursor", "gemini")
ADAPTER_NAMES = {"claude": "Claude Code", "codex": "Codex", "cursor": "Cursor", "gemini": "Gemini CLI"}
# Adapters outside the matrix (a feature's optional `outside_matrix` cells).
OUTSIDE_NAMES = {"opencode": "OpenCode", "pi": "Pi", "devin": "Devin"}
# group id -> heading, in document order
GROUPS = {
    "investigation": "Investigation and supervision",
    "authoring": "Storyboard authoring and discovery",
    "skills": "Skills and agents",
    "evidence": "Evidence capture",
    "checks": "Checks preview",
    "telemetry": "Telemetry, spend limits and decisions",
    "dev": "Developer gates",
}
BEGIN = "<!-- BEGIN parity matrix: generated by build/parity_md.py from docs/parity.json; do not edit by hand -->"
END = "<!-- END parity matrix -->"


def _kind(cell: str) -> str:
    if cell == "present":
        return "P"
    if cell.startswith("limit:"):
        return "L"
    if cell.startswith("na:"):
        return "N/A"
    return "?"


def render(data: dict) -> str:
    feats = {k: v for k, v in data.items() if not k.startswith("_")}
    counts = {a: {"P": 0, "L": 0, "N/A": 0} for a in ADAPTERS}
    for f in feats.values():
        for a in ADAPTERS:
            k = _kind(f["adapters"].get(a, ""))
            if k in counts[a]:
                counts[a][k] += 1
    lines: List[str] = [BEGIN, ""]
    lines.append(f"{len(feats)} features. P = present (a probe checks it), L = platform limit "
                 f"(cited below), N/A = not a parity item (reason below).")
    lines.append("")
    lines.append("| | " + " | ".join(ADAPTER_NAMES[a] for a in ADAPTERS) + " |")
    lines.append("|---|" + "---|" * len(ADAPTERS))
    for k in ("P", "L", "N/A"):
        lines.append(f"| {k} | " + " | ".join(str(counts[a][k]) for a in ADAPTERS) + " |")
    for group, heading in GROUPS.items():
        rows = [(fid, f) for fid, f in feats.items() if f.get("group") == group]
        if not rows:
            continue
        lines += ["", f"### {heading}", ""]
        lines.append("| Feature | " + " | ".join(ADAPTER_NAMES[a] for a in ADAPTERS) + " |")
        lines.append("|---|" + "---|" * len(ADAPTERS))
        notes: List[str] = []
        for fid, f in rows:
            cells = []
            for a in ADAPTERS:
                cell = f["adapters"].get(a, "")
                k = _kind(cell)
                cells.append(k)
                if k in ("L", "N/A"):
                    notes.append(f"- **{f['title']}**, {ADAPTER_NAMES[a]} ({k}): {cell.split(':', 1)[1].strip()}")
                elif (f.get("notes") or {}).get(a):
                    # a present cell's qualifier (e.g. notify-only)
                    notes.append(f"- **{f['title']}**, {ADAPTER_NAMES[a]} (P): {f['notes'][a]}")
            # The native and API adapters (opencode, pi, devin) are not matrix
            # columns; a feature may still say why they do not have it.
            for a, cell in (f.get("outside_matrix") or {}).items():
                notes.append(f"- **{f['title']}**, {OUTSIDE_NAMES.get(a, a)} (outside the matrix, "
                             f"{_kind(cell)}): {cell.split(':', 1)[1].strip()}")
            lines.append(f"| {f['title']} (`{fid}`) | " + " | ".join(cells) + " |")
        if notes:
            lines += [""] + notes
    allow = data.get("_claude_internal_hooks") or []
    lines += ["", "### Claude-only hooks outside the matrix", ""]
    if allow:
        for entry in allow:
            lines.append(f"- `{entry['script']}` on {entry['event']}: {entry['reason']}")
    else:
        lines.append("None: every hook in `adapters/claude/hooks/hooks.json` maps to a feature above.")
    lines += ["", END]
    return "\n".join(lines)


def update(current: str, data: dict) -> str:
    start, end = current.find(BEGIN), current.find(END)
    if start < 0 or end < start:
        raise ValueError("docs/parity.md lacks the generated-matrix markers")
    return current[:start] + render(data) + current[end + len(END):]


def main(argv: List[str]) -> int:
    data = json.loads(PARITY_JSON.read_text(encoding="utf-8"))
    current = PARITY_MD.read_text(encoding="utf-8")
    new = update(current, data)
    if "--check" in argv:
        if new != current:
            print("docs/parity.md is out of date: run python3 build/parity_md.py", file=sys.stderr)
            return 1
        return 0
    if new != current:
        PARITY_MD.write_text(new, encoding="utf-8")
        print("wrote docs/parity.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
